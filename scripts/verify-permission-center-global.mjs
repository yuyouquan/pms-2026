import assert from 'node:assert/strict'
import path from 'node:path'
import { loadTypeScriptModule } from './lib/typescript-module-loader.mjs'
const load = file => loadTypeScriptModule(path.resolve(file))
const lib = load('src/lib/permissionCenter.ts')
const constants = load('src/constants/permissionCenter.ts')
const { usePermissionStore: permissions } = load('src/stores/permission.ts')
const { useProjectStore: projects } = load('src/stores/project.ts')
const { useHrConfigStore: hr } = load('src/stores/hrConfig.ts')
const { useTransferStore: transfer } = load('src/stores/transfer.ts')
const empty = { version: 1, groups: [], roles: [], policies: [] }
const merged = permissions.persist.getOptions().merge({ permissionCenter: empty, globalRoles: [{ name: '管理组', members: ['stale-admin'] }] }, permissions.getState())
assert.deepEqual(merged.globalRoles.find(role => role.name === '管理组').members, [], 'hydration must revoke stale legacy admin membership')
assert.deepEqual(constants.getPermissionMenu('joint.plan').actions, ['view', 'edit'])
for (const menu of ['roadmap.table', 'roadmap.evolution']) assert.deepEqual(constants.getPermissionMenu(menu).actions, ['view', 'export', 'edit', 'create', 'delete'])
const migrated = lib.migrateLegacyPermissionCenter([{ name: '管理组', members: ['admin'] }, { name: '编辑组', members: ['legacy-editor'] }], { 编辑组: { 'configCenter:transferEdit': true, 'configCenter:hrModelEdit': true, 'roadmap:baseline': true } })
assert(migrated.policies.every(policy => lib.validateMenuPolicy(policy).ok), 'all migrated grants must use supported actions')
assert.equal(lib.evaluateMenuPermission(migrated, 'legacy-editor', 'config.transfer:整机产品项目:checklist', 'import'), true)
assert.equal(lib.evaluateMenuPermission(migrated, 'legacy-editor', 'config.hrPipeline:feeRate', 'edit'), true)
assert.equal(lib.evaluateMenuPermission(migrated, '演示用户04', 'hr.config/tech-tmg', 'edit'), true)
assert.equal(lib.evaluateMenuPermission(migrated, '演示用户04', 'hr.config/tech-tmg', 'import'), true)
assert.equal(lib.evaluateMenuPermission(migrated, '演示用户04', 'config.transfer:整机产品项目:review', 'export'), true)
assert(migrated.roles.filter(role => role.id.startsWith('compat:registry:')).every(role => !/ \/ (formal|budget|roadmap) \//.test(role.name)))
const role = { id: 'one', groupId: 'group-project', name: 'One', members: [] }
const model = { ...migrated, roles: [...migrated.roles, role], policies: [] }
const grant = (menuId, actions) => ({ ...lib.createEmptyMenuPolicy('one', menuId), users: ['scoped'], actions: ['view', ...actions] })
permissions.setState({ permissionCenter: { ...model, policies: [grant('config.hrPipeline:hrModel', ['edit'])] } })
projects.setState({ currentLoginUser: 'scoped' })
const before = hr.getState().data
hr.getState().addRecord('techTmg', { tmg: 'forbidden' })
assert.equal(hr.getState().data, before, 'HR config must not retain public write bypass')
assert.throws(() => hr.getState().setFeeRate(777), /权限/)
permissions.setState({ permissionCenter: { ...model, policies: [grant('hr.config/tech-tmg', ['edit'])] } })
hr.getState().addRecord('techTmg', { tmg: 'allowed' })
assert.equal(hr.getState().data.techTmg.length, before.techTmg.length + 1)
const beforeImport = hr.getState().data
hr.getState().importRecords('techTmg', [{ id: 'must-deny-import', tmg: 'no' }])
assert.equal(hr.getState().data, beforeImport, 'edit cannot imply import')
permissions.setState({ permissionCenter: { ...model, policies: [grant('config.transfer:整机产品项目:checklist', ['import'])] } })
const templates = transfer.getState().tmTemplateVersions
assert.equal(transfer.getState().importTransferTemplate('整机产品项目', 'review', templates['整机产品项目'].review[0].rows, 'scoped'), false)
assert.equal(transfer.getState().importTransferTemplate('整机产品项目', 'checklist', templates['整机产品项目'].checklist[0].rows, 'scoped'), true)
const teamBefore = transfer.getState().tmTeamConfigs
assert(transfer.getState().saveTransferTeamConfig('整机产品项目', teamBefore['整机产品项目'], 'scoped').length > 0)
assert.equal(transfer.getState().tmTeamConfigs, teamBefore)
console.log('Permission center global integration checks passed')
const numericPolicy = { ...lib.createEmptyMenuPolicy('one', 'project.view'), users: ['scoped'], actions: ['view'], data: { mode: 'conditions', conjunction: 'all', conditions: [{ id: 'progress', field: 'progress', operator: 'in', value: ['2', '10'] }] } }
assert.equal(lib.validateMenuPolicy(numericPolicy).ok, true, 'numeric list operator must accept valid numeric choices')
assert.equal(lib.evaluateMenuPermission({ ...model, policies: [numericPolicy] }, 'scoped', 'project.view', 'view', { progress: 2 }), true)
assert.equal(lib.validateMenuPolicy({ ...numericPolicy, data: { ...numericPolicy.data, conditions: [{ ...numericPolicy.data.conditions[0], value: ['invalid'] }] } }).ok, false)
assert.equal(lib.matchesPermissionCondition({ progress: 2 }, { field: 'progress', operator: 'in', value: ['2.0'] }, { kind: 'number' }), true)
assert.equal(lib.matchesPermissionCondition({ launch: '2026-09-28T00:00:00.000Z' }, { field: 'launch', operator: 'in', value: ['2026-09-28'] }, { kind: 'date' }), true)
const { useEnumStore: enums } = load('src/stores/enums.ts')
const enumBefore = enums.getState().rowsByType
assert.equal(await enums.getState().resetLocalConfig(() => false), false)
assert.equal(enums.getState().rowsByType, enumBefore, 'denied reset cannot replace any enum values')
console.log('Typed condition and enum reset guards passed')
const registryGrants = migrated.policies.filter(policy => policy.roleId.startsWith('compat:registry:'))
assert(registryGrants.length > 0)
assert(registryGrants.every(policy => !policy.actions.includes('delete') && !policy.actions.includes('export')), 'designated managers must not gain admin-only registry operations')
const malformed = lib.parsePermissionCenter({ ...model, roles: [{ ...role, description: { unexpected: 'object' } }], policies: [{ roleId: 'one', menuId: 'project.config', users: ['scoped'], actions: ['view', 'create'] }] })
assert.equal(malformed.roles.length, 0, 'invalid role display metadata must not enter the UI')
assert.equal(malformed.policies.length, 0, 'malformed nested policy must be removed before consumers inspect it')
const unknownFieldPolicy = { ...grant('project.view', []), data: { mode: 'conditions', conjunction: 'all', conditions: [{ id: 'dynamic', field: 'later-registered-field', operator: 'eq', value: 'allowed' }] } }
const structural = lib.parsePermissionCenter({ ...model, roles: [{ ...role, description: '' }], policies: [unknownFieldPolicy, { ...grant('project.config', ['create']), data: null }] })
assert.equal(structural.policies.length, 1, 'valid unknown metadata is retained for later registration while malformed data is dropped')
assert.equal(lib.evaluateMenuPermission(structural, 'scoped', 'project.view'), false)
console.log('Migration scope and corrupted persistence checks passed')
const globalMenus = load('src/lib/globalMenuPermissions.ts')
const scopedMenus = { ...model, policies: [grant('config.enum:brand', ['edit']), grant('hr.config/tech-tmg', ['export'])] }
// Use an actual registered enum leaf, independent of its display name.
const enumMenu = constants.PERMISSION_MENUS.find(menu => menu.id.startsWith('config.enum:'))
scopedMenus.policies[0] = grant(enumMenu.id, ['edit'])
assert.deepEqual(globalMenus.getAccessibleConfigGroups(scopedMenus, 'scoped').flatMap(group => group.children.map(leaf => `config.${leaf.key}`)), [enumMenu.id])
assert.deepEqual(globalMenus.getAccessibleHrGroups(scopedMenus, 'scoped').flatMap(group => group.children.map(leaf => `hr.${leaf.key}`)), ['hr.config/tech-tmg'])
permissions.setState({ permissionCenter: scopedMenus })
projects.setState({ currentLoginUser: 'scoped' })
assert.equal(globalMenus.canRunGlobalMenuAction('scoped', enumMenu.id, 'edit'), true)
permissions.setState({ permissionCenter: { ...model, policies: [] } })
assert.equal(globalMenus.canRunGlobalMenuAction('scoped', enumMenu.id, 'edit'), false, 'confirmation reads latest grants')
permissions.setState({ permissionCenter: scopedMenus })
projects.setState({ currentLoginUser: 'other-user' })
assert.equal(globalMenus.canRunGlobalMenuAction('scoped', enumMenu.id, 'edit'), false, 'old identity cannot finish a queued callback')
let resetChecks = 0
assert.equal(await enums.getState().resetLocalConfig(() => ++resetChecks === 1), false, 'enum reset re-checks authorization immediately before mutation')
assert.equal(resetChecks, 2)
assert.equal(enums.getState().rowsByType, enumBefore)
assert.equal(lib.matchesPermissionCondition({ progress: '' }, { field: 'progress', operator: 'eq', value: '0' }, { kind: 'number' }), false, 'missing numeric data cannot match zero')
console.log('Navigation isolation and live authorization checks passed')
