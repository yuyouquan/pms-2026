import assert from 'node:assert/strict'
import path from 'node:path'
import * as XLSX from 'xlsx'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader(), get = p => load(path.resolve(p))
const { getProjectSpaceModules, resolveProjectSpaceModule } = get('src/lib/projectSpaceNavigation.ts')
assert.deepEqual(getProjectSpaceModules({projectAttribute:'budget'}), ['resources','permission'])
assert.deepEqual(getProjectSpaceModules({projectAttribute:'roadmap'}), ['basic','permission'])
assert.equal(resolveProjectSpaceModule({projectAttribute:'budget'}, 'basic'), 'resources')
assert.equal(resolveProjectSpaceModule({projectAttribute:'roadmap'}, 'resources'), 'basic')
assert.equal(resolveProjectSpaceModule({projectAttribute:'formal'}, 'plan'), 'plan')
const { getProjectListFieldDefinitions, buildProjectSummaryRow } = get('src/lib/projectSummary.ts')
const fields = getProjectListFieldDefinitions('machine', [], '整机产品项目')
assert.equal(fields.find(f => f.key === 'fanTrialEnabled')?.defaultVisible, true)
assert.ok(fields.find(f => f.key === 'jiraProjects'))
const { initialProjects } = get('src/data/projects.ts')
const project = initialProjects.find(p => p.id === '3')
const row = buildProjectSummaryRow(project, fields)
const { getProjectListExportValue } = get('src/lib/projectListExport.ts')
const values = ['projectName','jiraProjects','fanTrialEnabled'].map(key => getProjectListExportValue(key,row))
assert.match(values[1], /https:\/\//)
assert.match(values[2], /尼日利亚.*30/)
assert.match(values[2], /肯尼亚.*20/)
assert.match(values[2], /印度.*15/)
const workbook = XLSX.utils.book_new()
XLSX.utils.book_append_sheet(workbook, XLSX.utils.aoa_to_sheet([['项目名称','JIRA项目','是否粉丝试用'],values]), '项目视图')
const roundTrip = XLSX.read(XLSX.write(workbook,{bookType:'xlsx',type:'buffer'}),{type:'buffer'})
assert.deepEqual(XLSX.utils.sheet_to_json(roundTrip.Sheets['项目视图'], {header:1})[1], values)
console.log('PASS restricted space navigation, reachable fan-trial column and complete Excel values/URLs')
