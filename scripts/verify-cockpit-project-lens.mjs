import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader()
const { cockpitProjectColumns } = load(path.resolve('src/components/cockpit/cockpitProjectLens.ts'))
const { useCockpitUiStore, createCockpitPreferences } = load(path.resolve('src/stores/cockpitUi.ts'))
const { cockpitRatios } = load(path.resolve('src/components/cockpit/cockpitData.ts'))
const columns = ['name', 'category', 'status', 'annual', 'estimate', 'budget', 'cumulativeBudget', 'actual', 'deviation', 'toDate', 'annualExecution', 'cumulative'].map(key => ({ key, render: row => row[key] }))
assert.equal(cockpitProjectColumns(columns, 'all'), columns, 'all fields keep original order and objects')
const budget = cockpitProjectColumns(columns, 'budget'), actual = cockpitProjectColumns(columns, 'actual')
assert.deepEqual(budget.map(column => column.key), ['name', 'budget', 'estimate', 'deviation', 'annual'])
assert.deepEqual(actual.map(column => column.key), ['name', 'actual', 'cumulative', 'toDate', 'budget', 'annualExecution'])
assert.equal(budget[1], columns.find(column => column.key === 'budget'), 'projection keeps existing render/calculation bindings')
assert.equal(columns[1].key, 'category', 'no input mutation')
assert.deepEqual(cockpitProjectColumns(columns.filter(column => column.key !== 'estimate'), 'budget').map(column => column.key), ['name', 'budget', 'deviation', 'annual'], 'absent definitions are not invented')
const fallback = { actual: { cost: 20 }, cumulative: { cost: 40 }, cumulativeBudget: undefined, budget: undefined }
assert.equal(actual[2].render(fallback).cost, 40, 'actual comparison displays the real execution denominator')
assert.equal(cockpitRatios(fallback, 'cost').toDate, 50)
assert.equal(createCockpitPreferences().projectLens, 'all')
const state = () => useCockpitUiStore.getState()
state().updatePreferences('甲', { projectLens: 'budget', projectSearch: 'DEMO017', mode: 'cost' })
state().updateOverviewTable('甲', 'project', { widths: { name: 290 }, sort: { key: 'status', descending: true } })
state().updatePreferences('甲', { projectLens: 'actual' })
assert.equal(state().preferencesByActor['甲'].projectSearch, 'DEMO017')
assert.equal(state().preferencesByActor['甲'].overviewTables.project.sort.key, 'status', 'column focus does not overwrite sorting memory')
state().resetFilters('甲')
assert.equal(state().preferencesByActor['甲'].projectLens, 'actual', 'filter reset preserves reading view')
state().updatePreferences('乙', { mode: 'labor' })
assert.equal(state().preferencesByActor['乙'].projectLens, 'all', 'actors independent')
console.log('PASS cockpit project lens: primary amounts first, original bindings/order, missing definitions, cumulative execution denominator, immutable choices and isolated presentation memory')
