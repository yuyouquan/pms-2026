import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader()
const { cockpitTrendOption, cockpitAllocationOption, cockpitComparisonOption } = load(path.resolve('src/components/cockpit/cockpitChartOptions.ts'))
const { createCockpitPreferences, useCockpitUiStore } = load(path.resolve('src/stores/cockpitUi.ts'))
const source = [{ key: 'budget', label: '预算', color: '#000', values: [0, undefined, -20, 80] }, { key: 'actual', label: '核算', color: '#000', values: [2, 3, undefined, 4] }]
const line = cockpitTrendOption(['2026-01','2026-02','2026-03','2026-04'], source, [], false, 'cost')
assert.deepEqual(line.series[0].data, [0, null, -20, 80], 'zero, absent and signed values remain distinct')
assert.equal(line.series[0].connectNulls, false, 'no interpolation over absent source months')
assert.equal(line.yAxis.min, undefined, 'no zero minimum clipping negative values')
assert.equal(line.tooltip.valueFormatter(80), '80.0 万元')
assert.equal(line.tooltip.valueFormatter(null), '—')
const hidden = cockpitTrendOption(['x'], source, ['budget'], true, 'labor')
assert.deepEqual(hidden.series.map(row => row.id), ['actual'])
assert.equal(hidden.series[0].stack, undefined, 'categories are separate rows, never stacked')
assert.equal(hidden.grid.length, 2, 'hiding a category retains aligned rows')
assert.equal(hidden.series[0].xAxisIndex, 1, 'visible data stays in its own category row')
const category = cockpitTrendOption(['2026-01','2026-02','2026-03','2026-04'], source, [], true, 'cost')
assert.equal(category.grid.length, source.length)
assert.deepEqual(category.xAxis.map(row => row.gridIndex), [0, 1])
assert.deepEqual(category.series.map(row => row.yAxisIndex), [0, 1])
assert.deepEqual(category.series[0].data, [0, null, -20, 80], 'small multiples preserve source values')
assert.equal(new Set(category.yAxis.map(row => `${row.min}:${row.max}:${row.interval}`)).size, 1, 'identical scale for fair category comparison')
assert.ok(category.yAxis[0].min < -20 && category.yAxis[0].max > 80, 'signed values and labels fit within axis bounds')
assert.ok(category.series.every(row => row.label.show && row.itemStyle.color === category.series[0].itemStyle.color), 'direct labels and system purple for every row')
assert.equal(category.series[0].label.formatter({ value: 0 }), '0.0')
assert.equal(category.series[0].label.formatter({ value: null }), '')
assert.equal(category.series[0].label.formatter({ value: -20 }), '-20.0')
const emptyCategory = cockpitTrendOption(['2026-01'], [{key:'empty',label:'空',values:[undefined]}], [], true, 'labor')
assert.ok(emptyCategory.yAxis[0].max > emptyCategory.yAxis[0].min)
assert.deepEqual(emptyCategory.series[0].data, [null])
assert.equal(cockpitTrendOption([], source, ['budget', 'actual'], false, 'cost').series.length, 0)
assert.equal(cockpitTrendOption(Array.from({ length: 53 }, (_, i) => `${i}`), source, [], true, 'labor').dataZoom[0].endValue, 11)
const weekly = cockpitTrendOption(Array.from({length:53}, (_,i) => `${i}`), source, [], true, 'labor')
assert.deepEqual(weekly.dataZoom[0].xAxisIndex, [0,1], 'all rows share the same time window')
assert.deepEqual(source[0].values, [0, undefined, -20, 80], 'mapping does not mutate resource data')
const pie = cockpitAllocationOption([{ label: '已分类', days: 0 }, { label: '未归类', days: 15 }])
assert.deepEqual(pie.series[0].data.map(row => [row.name, row.value]), [['未归类',15]], 'actual person-days, no invented classification')
assert.equal(cockpitAllocationOption([{ label: 'x', days: 0 }]).series[0].data.length, 0, 'empty dataset never becomes an equal-slice chart')
const bars = cockpitComparisonOption([{ key: 'x', name: '类别', budget: { cost: -10 }, actual: { labor: 2 } }], 'cost')
assert.deepEqual(bars.series.map(row => row.data), [[-10],[null]], 'comparison uses requested unit and preserves missing values')
assert.equal(createCockpitPreferences().shareTab, 'category', 'default chart shows existing project classifications')
assert.equal(createCockpitPreferences().overviewOpen, false, 'no ledger table on default dashboard')
useCockpitUiStore.getState().updatePreferences('甲', { overviewOpen: true, projectSearch: 'DEMO017', projectLens: 'budget' })
useCockpitUiStore.getState().resetFilters('甲')
assert.equal(useCockpitUiStore.getState().preferencesByActor['甲'].overviewOpen, true, 'reading context survives filter changes and project navigation')
assert.equal(createCockpitPreferences().overviewOpen, false, 'other actors default closed')
console.log('PASS ECharts mapping: missing/zero/negative values, source units, legend visibility, week zoom, genuine person-days, immutable data and actor-scoped detail state')
