import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
import { createCurrentDatasetStorage } from './lib/mock-dataset-storage.mjs'
globalThis.localStorage = createCurrentDatasetStorage()
globalThis.window = { localStorage }
const load = createTypeScriptModuleLoader()
const storeModule = load(path.resolve('src/stores/mrVersionPlan.ts'))
const store = storeModule.createMrVersionPlanStore({ initialState: { tosInstancesByProjectId: {} }, now: () => '2026-09-23T08:00:00.000Z' })
assert.equal(typeof store.getState().syncTosInstancesFromLevel1, 'function', 'MR plans must automatically reconcile against level-one business nodes')
const candidate = (value,id) => ({value,label:value,sourceLevel1TaskId:id,planStartDate:'',planEndDate:'',disabled:true})
const candidates = [candidate('16.1.0.120','launch-120'),candidate('16.1.0.125','maintenance-125')]
store.getState().syncTosInstancesFromLevel1('2',candidates)
let instances = store.getState().tosInstancesByProjectId['2']
assert.deepEqual(instances.map(row=>row.tosVersion),['16.1.0.120','16.1.0.125'],'both business stages create MR rows even without dates')
assert.ok(instances.every(row=>row.activities.length>0),'new MR rows copy the latest published template')
const first = instances[0]
const leaf = first.activities.find(row=>row.parentId!==null)
store.setState({tosInstancesByProjectId:{...store.getState().tosInstancesByProjectId,'2':instances.map(row=>row===first?{...row,dates:{[leaf.id]:'2027-01-04'}}:row)}})
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120'),candidates[1]])
instances = store.getState().tosInstancesByProjectId['2']
const renamed = instances.find(row => row.sourceLevel1TaskId === 'launch-120')
assert.equal(renamed.dates[leaf.id],'2027-01-04','renaming a level-one node preserves entered MR dates')
assert.equal(renamed.tosVersion,'16.1.0.130')
assert.deepEqual(renamed.activities,first.activities,'existing MR template snapshots stay unchanged')
store.setState({machinePlansByKey:{'machine::16.1.0.130':{projectId:'machine',tosProjectId:'2',tosVersion:'16.1.0.130',transferType:'1',dates:{[leaf.id]:'2027-01-05'},updatedBy:'tester',updatedAt:'2026-09-23'}}})
store.getState().syncTosInstancesFromLevel1('2',[], 'Slim')
store.getState().reconcileMachinePlans({today:'2027-01-01',tosProjects:[],machineProjects:[],latestPublishedLevel1ByProjectId:{}})
assert.equal(store.getState().tosDownstreamByType.Full['2'].machinePlansByKey['machine::16.1.0.130'].dates[leaf.id], '2027-01-05', 'temporarily hidden main-type MR rows retain downstream machine dates')

assert.deepEqual(store.getState().tosInstancesByProjectId['2'], [], 'main type switch changes the visible projection')
const switchSnapshot = storeModule.partializeMrVersionPlanState(store.getState())
store.setState(storeModule.migrateMrVersionPlanState(switchSnapshot, storeModule.MR_VERSION_PLAN_STORE_VERSION))
assert.equal(store.getState().tosDownstreamByType.Full['2'].machinePlansByKey['machine::16.1.0.130'].dates[leaf.id], '2027-01-05', 'inactive downstream dates survive persistence')
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120'),candidates[1]], 'Full')
assert.equal(store.getState().tosInstancesByProjectId['2'].find(row => row.sourceLevel1TaskId === 'launch-120').dates[leaf.id], '2027-01-04', 'switching main type and refreshing must preserve prior MR dates')
assert.equal(store.getState().machinePlansByKey['machine::16.1.0.130'].dates[leaf.id], '2027-01-05', 'restoring the main type restores its downstream dates')
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','slim-same-version')], 'Slim')
assert.equal(store.getState().machinePlansByKey['machine::16.1.0.130'], undefined, 'same version in another type must not inherit machine dates')
store.getState().reconcileMachinePlans({today:'2027-01-01',tosProjects:[],machineProjects:[],latestPublishedLevel1ByProjectId:{}})
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120'),candidates[1]], 'Full')
assert.equal(store.getState().machinePlansByKey['machine::16.1.0.130'].dates[leaf.id], '2027-01-05', 'same-version type round trip preserves downstream data')
// A stopped machine must not reappear when an inactive type is restored.
store.setState({stopReleaseRecords:[{id:'stop-machine',projectId:'machine',projectName:'machine',stopDate:'2027-01-01',operator:'tester',operatedAt:'2026-09-23'}]})
store.getState().syncTosInstancesFromLevel1('2',[], 'Slim')
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120'),candidates[1]], 'Full')
assert.equal(store.getState().machinePlansByKey['machine::16.1.0.130'], undefined, 'restoring a type must respect stop-release records')
const before = store.getState()
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120'),candidates[1]])
assert.equal(store.getState(),before,'reconciliation must be idempotent to avoid render/storage loops')
store.getState().syncTosInstancesFromLevel1('6',[candidate('17.1.0.120','launch-120')])
store.getState().syncTosInstancesFromLevel1('2',[candidate('16.1.0.130','launch-120')])
assert.equal(store.getState().tosInstancesByProjectId['2'].length,1,'deleting a level-one node removes its MR content')
assert.equal(store.getState().tosInstancesByProjectId['6'].length,1,'other projects are isolated')
const serialized = storeModule.partializeMrVersionPlanState(store.getState())
const hydrated = storeModule.migrateMrVersionPlanState(serialized,storeModule.MR_VERSION_PLAN_STORE_VERSION)
assert.equal(hydrated.tosInstancesByProjectId['2'][0].sourceLevel1TaskId,'launch-120','source identity survives refresh')
store.getState().syncTosInstancesFromLevel1('2',[])
assert.deepEqual(store.getState().tosInstancesByProjectId['2'],[],'removing the final node clears the project MR content')
const projectStore = load(path.resolve('src/stores/project.ts')).useProjectStore
const planStore = load(path.resolve('src/stores/plan.ts')).usePlanStore
const rules = load(path.resolve('src/lib/level1PlanRules.ts'))
const shared = load(path.resolve('src/lib/level1SharedBusinessTasks.ts'))
const types = load(path.resolve('src/lib/tosTypeRules.ts'))
const adapter = load(path.resolve('src/lib/tosMrLevel1Sync.ts'))
const project = projectStore.getState().projects.find(p=>p.id==='2')
const tasks = rules.buildTosLevel1Tasks()
const parent = tasks.find(t=>t.taskName==='上市迭代阶段')
const child = {id:'sync-child',stableId:'sync-child',parentId:parent.id,taskName:'16.1.0.150',order:0,planStartDate:'',planEndDate:''}
const typeRows = types.buildTosTypeRows(project.versionTypes||[],project.versionType||'',projectStore.getState().tosTypeConfigsByProjectId['2'])
const sourceType = types.getMainTosType(typeRows)
const scope = shared.getLevel1BusinessScopeKey('2','tos',sourceType)
const sharedTasks = shared.captureLevel1BusinessTasks('tOS版本项目',[...tasks,child])
const sourceInput = {project,tosTypeRows:typeRows,tosTypeVersionsByKey:{},publishedSnapshots:{},fallbackVersions:[],tosTypePlanData:{},sharedBusinessTasks:{[scope]:sharedTasks}}
assert.equal(adapter.selectActiveTosMrTasks(sourceInput).some(t=>t.taskName===child.taskName),true,'shared nodes are authoritative even before first publication')
assert.equal(adapter.selectActiveTosMrTasks({...sourceInput,sharedBusinessTasks:{}}),null,'missing source is not authoritative empty')
const listeners = new Map()
const events = {localStorage,addEventListener:(name,listener)=>listeners.set(name,listener),removeEventListener:(name)=>listeners.delete(name)}
const stop = load(path.resolve('src/hooks/useTosMrLevel1Sync.ts')).startTosMrLevel1Sync(events)
await Promise.resolve(); await Promise.resolve()
planStore.getState().setLevel1BusinessTasks(scope,'tOS版本项目',[...tasks,child])
await Promise.resolve(); await Promise.resolve()
assert.equal(storeModule.useMrVersionPlanStore.getState().tosInstancesByProjectId['2'].some(row=>row.tosVersion===child.taskName),true,'source subscription updates MR while its page is closed')
const external = JSON.parse(localStorage.getItem('pms-plan-store'))
external.state.level1BusinessTasksByScope[scope] = shared.captureLevel1BusinessTasks('tOS版本项目',tasks)
localStorage.setItem('pms-plan-store',JSON.stringify(external))
listeners.get('storage')({key:'pms-plan-store',storageArea:localStorage})
await Promise.resolve(); await Promise.resolve()
assert.deepEqual(storeModule.useMrVersionPlanStore.getState().tosInstancesByProjectId['2']||[],[],'cross-tab source deletion updates MR without echo loops')
stop()
console.log('PASS tOS MR automatic add/delete/rename, incomplete dates, project isolation and persistence')
process.exit(0)
