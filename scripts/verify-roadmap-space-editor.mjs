#!/usr/bin/env node
import assert from 'node:assert/strict'
import { loadTypeScriptModule, projectRoot } from './lib/source-contract.mjs'
const root = projectRoot(import.meta.url)
const { buildRoadmapSpaceEditPayload, toRoadmapSpaceFormProject } = loadTypeScriptModule(root, 'src/lib/roadmapSpaceEditor.ts')
const { buildManualProjectSpaceUpdate } = loadTypeScriptModule(root, 'src/lib/manualProjectCompletion.ts')
const { getMissingProjectInfoFields } = loadTypeScriptModule(root, 'src/lib/projectInfoCompletion.ts')
const { RESOURCE_REGISTRY_PROJECTS } = loadTypeScriptModule(root, 'src/mock/projectRegistry.ts')
const project = RESOURCE_REGISTRY_PROJECTS.find(item => item.id === 'mock-roadmap-incomplete')
const form = toRoadmapSpaceFormProject(project)
assert.equal(form.projectCode, project.name, 'old project-name control displays the canonical name, not the registry code')
assert.equal(form.str5Date, '')
assert.equal(form.launchDate, '')
const noChanges = buildRoadmapSpaceEditPayload(project, form)
assert.deepEqual(noChanges.infoValues, {}, 'opening and saving preserves omitted/historical fields')
const input = { ...form, projectCode: 'cannot change identity', str5Date: '2026-10-01', launchDate: '2026-11-01', str5Estimated: true }
const payload = buildRoadmapSpaceEditPayload(project, input)
assert.deepEqual(payload.infoValues, { str5Date: '2026-10-01', launchDate: '2026-11-01', str5Estimated: true })
const saved = buildManualProjectSpaceUpdate(project, payload)
assert.deepEqual(getMissingProjectInfoFields(saved), [])
for (const key of ['id', 'name', 'projectCode', 'projectAttribute', 'boundFormalProjectId', 'createdAt', 'createdBy', 'status', 'healthStatus', 'responsiblePersons']) assert.deepEqual(saved[key], project[key], key)
assert.deepEqual(saved.fieldValues.machineSpm, project.fieldValues.machineSpm)
assert.equal(saved.fieldValues.fanTrialEnabled, project.fieldValues.fanTrialEnabled)
const changed = buildRoadmapSpaceEditPayload(project, { ...form, startRam: '12GB', developMode: 'ODC', firstSaleTosVersionId: '18.1', machineProjectType: '整机-平板', remark: '仅修改旧表单字段' })
assert.equal(changed.projectSecondaryCategory, '整机-平板')
assert.equal(changed.infoValues.startingRam, '12GB')
assert.equal(changed.infoValues.developmentMode, 'ODC')
assert.equal(changed.infoValues.firstSaleTosVersion, '18.1')
const dateOnly = buildManualProjectSpaceUpdate({ ...project, fieldValues: { ...project.fieldValues, fanTrialEnabled: '是', fanTrialCountries: [{ country: '印度', quantity: 10 }] } }, payload)
assert.deepEqual(dateOnly.fieldValues.fanTrialCountries, [{ country: '印度', quantity: 10 }])
console.log('PASS original roadmap form mapping, completion, identity, responsibility and omitted-field preservation')
const chipMappings = [{ id: 'new-chip', chipCode: 'NEW-CHIP', chipModel: 'NEW-MODEL', chipPlatform: 'NEW-PLATFORM' }]
const chipChange = buildRoadmapSpaceEditPayload(project, { ...form, chipCode: 'NEW-CHIP' }, chipMappings)
assert.equal(chipChange.infoValues.chipModel, 'NEW-MODEL')
assert.equal(chipChange.infoValues.chipPlatform, 'NEW-PLATFORM')
assert.deepEqual(buildRoadmapSpaceEditPayload(project, form, chipMappings).infoValues, {}, 'unchanged historical chip keeps its stored model and platform')
console.log('PASS chip changes update read-only model/platform; historical chips remain intact')
