import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const get = createTypeScriptModuleLoader()
const { createInlineFieldSession } = get(path.resolve('src/components/project-resources/inlineFieldSession.ts'))
let persisted = 'saved', changes = 0
const session = createInlineFieldSession(() => changes++)
session.begin(persisted)
session.change('new')
assert.equal(persisted, 'saved')
assert.equal(session.leave(true, value => persisted = value), true)
assert.equal(session.state.editing, true, 'popup interaction is inside editor')
assert.equal(persisted, 'saved')
assert.equal(session.leave(false, value => persisted = value), true)
assert.equal(persisted, 'new')
assert.equal(session.state.editing, false)
session.begin(persisted)
session.change('invalid')
assert.equal(session.save(() => { throw new Error('invalid value') }), false)
assert.equal(session.state.editing, true)
assert.equal(session.state.value, 'invalid')
assert.equal(session.state.error, 'invalid value')
session.cancel()
assert.equal(session.state.editing, false)
assert.equal(persisted, 'new')
session.begin(persisted)
session.change('enter')
assert.equal(session.save(value => persisted = value), true)
assert.equal(persisted, 'enter')
assert.ok(changes > 5)
console.log('PASS actual field session handlers: edit/outside/popup/Enter/Escape/failed save retains input')
