import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader()
const { useCockpitUiStore, createCockpitPreferences } = load(path.resolve('src/stores/cockpitUi.ts'))
const state = () => useCockpitUiStore.getState(), read = actor => state().preferencesByActor[actor]
const focus = (actor, dates) => state().focusPeriod(actor, { dates, scopePreference: 'all', shareScopePreferences: { research: 'software', category: 'all' } })
assert.deepEqual(createCockpitPreferences().periodHistory, [])
state().updatePreferences('甲', { dates: ['2026-10-01', '2026-12-31'], mode: 'cost', departments: ['产品部'], overviewTab: 'project', projectSearch: 'DEMO017' })
assert.equal(focus('甲', ['2026-11-01', '2026-11-30']), true)
const first = read('甲')
assert.deepEqual(first.periodHistory, [['2026-10-01', '2026-12-31']])
assert.equal(focus('甲', ['2026-11-09', '2026-11-15']), true)
assert.deepEqual(read('甲').periodHistory, [['2026-10-01', '2026-12-31'], ['2026-11-01', '2026-11-30']])
assert.deepEqual(first.periodHistory, [['2026-10-01', '2026-12-31']], 'previous snapshots immutable')
assert.equal(focus('甲', ['2026-11-09', '2026-11-15']), false, 'same window adds no history')
assert.equal(focus('甲', ['2026-10-01', '2026-12-31']), false, 'focus cannot widen the current period')
assert.equal(focus('甲', ['2026-11-31', '2026-11-31']), false, 'invalid calendar dates rejected')
state().updatePreferences('甲', { departments: ['硬件部'], mode: 'labor' })
assert.equal(state().returnToPeriod('甲'), true)
assert.deepEqual(read('甲').dates, ['2026-11-01', '2026-11-30'])
assert.deepEqual(read('甲').departments, ['硬件部'], 'return restores dates only, keeps subsequent department changes')
assert.equal(read('甲').mode, 'labor')
assert.equal(read('甲').overviewTab, 'project')
assert.equal(read('甲').projectSearch, 'DEMO017')
assert.equal(read('甲').shareScopePreferences.research, 'software')
state().updatePreferences('乙', { dates: ['2026-01-01', '2026-12-31'] })
assert.equal(focus('乙', ['2026-02-01', '2026-02-28']), true)
assert.equal(read('甲').periodHistory.length, 1, 'actors remain isolated')
assert.equal(state().returnToPeriod('甲'), true)
assert.deepEqual(read('甲').dates, ['2026-10-01', '2026-12-31'])
assert.equal(state().returnToPeriod('甲'), false, 'empty history is a no-op')
focus('甲', ['2026-10-01', '2026-10-31'])
state().updatePreferences('甲', { dates: ['2026-09-01', '2026-09-30'] })
assert.deepEqual(read('甲').periodHistory, [], 'manual date changes start a new analysis path')
focus('甲', ['2026-09-01', '2026-09-07'])
state().resetFilters('甲')
assert.deepEqual(read('甲').periodHistory, [], 'global reset clears history')
assert.equal(read('乙').periodHistory.length, 1, 'reset cannot clear another actor')
state().updatePreferences('甲', { dates: ['2026-01-01', '2026-01-31'] })
for (let day = 30; day >= 20; day--) focus('甲', ['2026-01-01', `2026-01-${day}`])
assert.equal(read('甲').periodHistory.length, 8, 'bounded choices-only memory')
assert.deepEqual(read('甲').periodHistory.at(-1), ['2026-01-01', '2026-01-21'], 'last period always available')
console.log('PASS cockpit period history: nested return, strict narrowing, no-op/invalid protection, immutable choices, per-user isolation, date-only restore, manual/reset clearing and bounded memory')
