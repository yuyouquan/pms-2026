import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader()
const { useCockpitUiStore, createCockpitPreferences } = load(path.resolve('src/stores/cockpitUi.ts'))
const read = actor => useCockpitUiStore.getState().preferencesByActor[actor]
const update = (actor, patch) => useCockpitUiStore.getState().updatePreferences(actor, patch)
const initial = createCockpitPreferences(new Date('2027-01-15T12:00:00'))
assert.deepEqual(initial.dates, ['2027-01-01', '2027-12-31'], 'fresh year uses the current calendar year')
assert.equal(initial.scopePreference, undefined, 'live resources still choose the initial department scope')
assert.deepEqual(initial.shareScopePreferences, {})
update('甲', { dates: ['2026-10-01', '2026-12-31'], mode: 'cost', overviewTab: 'project', projectSearch: 'DEMO017', departments: ['产品部'], scopePreference: 'all', shareScopePreferences: { research: 'software', category: 'all' } })
const before = read('甲')
update('乙', { projectSearch: '另一位用户', mode: 'labor' })
assert.equal(read('乙').overviewTab, 'category')
assert.equal(read('甲'), before, 'switching identities does not mutate the first user context')
update('甲', { trendTab: 'category', grain: 'week' })
assert.equal(read('甲').mode, 'cost')
assert.deepEqual(read('甲').dates, ['2026-10-01', '2026-12-31'])
assert.equal(read('甲').projectSearch, 'DEMO017', 'incremental updates preserve navigation context')
assert.equal(before.trendTab, 'resource', 'previous snapshots remain immutable')
useCockpitUiStore.getState().resetFilters('甲')
const reset = read('甲'), defaults = createCockpitPreferences()
assert.deepEqual(reset.dates, defaults.dates)
assert.equal(reset.scopePreference, undefined)
assert.deepEqual(reset.departments, [])
assert.deepEqual(reset.shareScopePreferences, {})
assert.equal(reset.projectCategory, 'all')
assert.equal(reset.projectSearch, '')
assert.equal(reset.mode, 'cost', 'filter reset preserves presentation units')
assert.equal(reset.overviewTab, 'project', 'filter reset preserves selected view')
assert.equal(reset.trendTab, 'category')
assert.equal(reset.grain, 'week')
assert.equal(read('乙').projectSearch, '另一位用户', 'reset never clears another identity')
assert.ok(Object.keys(reset).every(key => ['view', 'dates', 'periodHistory', 'scopePreference', 'departments', 'mode', 'trendTab', 'grain', 'hiddenTrendSeries', 'shareTab', 'shareScopePreferences', 'overviewOpen', 'overviewTab', 'projectCategory', 'projectSearch', 'overviewTables', 'rankingCategory', 'projectLens'].includes(key)), 'store holds choices only, no project facts or permission results')
console.log('PASS cockpit navigation context: calendar defaults, per-user isolation, immutable updates, filter reset and presentation retention')
