import assert from 'node:assert/strict'
import path from 'node:path'
import { createTypeScriptModuleLoader } from './lib/typescript-module-loader.mjs'
const load = createTypeScriptModuleLoader()
const permission = load(path.resolve('src/stores/permission.ts'))
assert.equal(typeof permission.getSyncedProjectRoles, 'function', 'stable source-role selector is required')
const { usePermissionStore, hasPermission, getSyncedProjectRoles } = permission
const { useProjectTeamStore } = load(path.resolve('src/stores/projectTeam.ts'))
const { canExecuteProjectTeamWrite, projectTeamScopeToken } = load(path.resolve('src/lib/projectTeamMutationGuard.ts'))
const { useRolePermissionTemplateStore } = load(path.resolve('src/stores/rolePermissionTemplates.ts'))
const member = '演示用户10', admin = '演示用户01', id = '1'
usePermissionStore.getState().ensurePermissionCenter()
const team = useProjectTeamStore.getState()
team.syncProjects([{ id, type: '整机产品项目', mockTeamSourceId: 'legacy:1' }])
let roles = getSyncedProjectRoles(id)
assert(roles.length >= 3)
const spm = roles.find(row => row.ipmRoleCode === 'RJPM')
assert(spm)
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), false)
const toggle = (keys, enabled = true, roleId = spm.id) => usePermissionStore.getState().toggleProjectRolePermissions(admin, id, { source: 'ipm', id: roleId }, keys, enabled)
assert.equal(toggle(['basicInfo:编辑']).ok, true)
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), true)
assert.equal(hasPermission(member, id, 'plan:二级计划-编辑'), false)
const live = { currentLoginUser: member, selectedProject: { id } }
assert.equal(canExecuteProjectTeamWrite(member, id, live, id, 'basicInfo:编辑'), true)
assert.equal(canExecuteProjectTeamWrite(member, id, live, id, 'resource:laborEdit'), false)
assert.equal(canExecuteProjectTeamWrite(member, id, live), false, 'responsibility-only writes remain denied')
assert.equal(toggle(['basicInfo:编辑'], false).ok, true)
assert.equal(canExecuteProjectTeamWrite(member, id, live, id, 'basicInfo:编辑'), false, 'revoked callback denies')
usePermissionStore.getState().setRolesForProject(id, [{ name: 'SPM', isFixed: false, members: [member], departments: ['示例研发部'] }])
usePermissionStore.getState().setRolePermissionsForProject(id, { SPM: { 'basicInfo:编辑': true } })
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), false, 'same-name local and department grants never elevate')
assert.equal(toggle(['basicInfo:编辑', 'plan:一级计划-编辑']).ok, false)
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), false)
assert.equal(toggle(['basicInfo:编辑']).ok, true)
const rd = roles.find(row => row.ipmRoleCode === 'RD')
assert.equal(toggle(['basicInfo:编辑'], true, rd.id).ok, true)
assert.equal(toggle(['basicInfo:编辑'], false).ok, true)
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), true, 'multi-role union survives one revoke')
assert.equal(toggle(Object.keys(rd.grants).concat('basicInfo:编辑'), false, rd.id).ok, true)
const template = useRolePermissionTemplateStore.getState().templatesByType['整机产品项目'].find(row => row.ipmRoleCode === 'RD')
useRolePermissionTemplateStore.getState().updateTemplateGrants(admin, '整机产品项目', template.id, ['basicInfo:编辑'], true)
team.refreshMock()
assert.equal(hasPermission(member, id, 'basicInfo:编辑'), false, 'refresh cannot reset explicit empty copy')
assert.equal(toggle(['projectPermission:manageRoles', 'plan:导出'], true).ok, true)
assert.equal(usePermissionStore.getState().toggleProjectRolePermissions(member, id, { source: 'ipm', id: spm.id }, ['projectPermission:manageRoles', 'plan:导出'], false).ok, true)
assert.equal(hasPermission(member, id, 'projectPermission:manageRoles'), false)
assert.equal(hasPermission(member, id, 'plan:导出'), false)
assert.equal(usePermissionStore.getState().toggleProjectRolePermissions(member, id, { source: 'ipm', id: spm.id }, ['projectPermission:manageRoles'], true).ok, false)
const openingSourceToken = projectTeamScopeToken(id)
team.syncProjects([{ id, type: '整机产品项目', sourceBid: 'EXT-001' }])
assert.equal(canExecuteProjectTeamWrite(member, id, live, id, 'basicInfo:查看', openingSourceToken), false, 'source rebind invalidates old callbacks even when new role permits same key')
assert.equal(getSyncedProjectRoles(id).some(row => row.id === spm.id), false, 'binding changes source identity')
assert.equal(toggle(['basicInfo:编辑']).ok, false, 'stale source-role mutation rejects')
assert.equal(hasPermission(admin, id, 'plan:一级计划-编辑'), true)
console.log('PASS source grants, employee identity, role union, copy isolation and operation guards')

// The action checks used by real resource stores and project writes consume the source union.
const { useProjectStore } = load(path.resolve('src/stores/project.ts'))
const { canResourceAction } = load(path.resolve('src/lib/hrProjectRegistry.ts'))
useProjectStore.getState().setProjects(rows => rows.map(row => row.id === id ? { ...row, sourceBid: 'EXT-001' } : row))
const current = useProjectStore.getState().projects.find(row => row.id === '1')
useProjectStore.setState({ currentLoginUser: member, selectedProject: current })
useProjectTeamStore.getState().syncProjects([{ ...current, sourceBid: 'EXT-001' }])
const bound = getSyncedProjectRoles(id).find(row => row.ipmRoleCode === 'RJPM')
const apply = (keys, enabled) => usePermissionStore.getState().toggleProjectRolePermissions(admin, id, { source: 'ipm', id: bound.id }, keys, enabled)
assert.equal(apply(['resource:laborEdit'], true).ok, true)
assert.equal(canResourceAction({ pmsProjectId: id }, 'laborEdit', id, member), true)
assert.equal(canResourceAction({ pmsProjectId: id }, 'createVersion', id, member), false)
assert.equal(apply(['resource:laborEdit'], false).ok, true)
assert.equal(canResourceAction({ pmsProjectId: id }, 'laborEdit', id, member), false)
assert.equal(apply(['basicInfo:编辑'], true).ok, true)
assert(useProjectStore.getState().updateProject(id, { projectDescription: 'source grant verified' }, member), 'real project edit accepts exact source grant')
assert.equal(apply(['basicInfo:编辑'], false).ok, true)
const rdBound = getSyncedProjectRoles(id).find(row => row.ipmRoleCode === 'RD')
usePermissionStore.getState().toggleProjectRolePermissions(admin, id, { source: 'ipm', id: rdBound.id }, ['basicInfo:编辑'], false)
assert.equal(useProjectStore.getState().updateProject(id, { projectDescription: 'denied' }, member), null, 'real project edit denies revoked grant')
assert.equal(apply(['resource:createVersion'], true).ok, true)
assert.equal(hasPermission(member, id, 'resource:createVersion'), true)
// Membership changes by employee ID, never by a same-name person's role.
const snapshot = useProjectTeamStore.getState().teamsByProjectId[id]
useProjectTeamStore.setState(state => ({ teamsByProjectId: { ...state.teamsByProjectId, [id]: { ...snapshot, members: snapshot.members.map(row => ({ ...row, employeeId: 'OTHER-ID' })) } } }))
assert.equal(getSyncedProjectRoles(id).length > 0, true, 'source definitions remain when member leaves')
assert.equal(hasPermission(member, id, 'resource:createVersion'), false)
// Parent scope moves invalidate an already-open child callback.
useProjectTeamStore.getState().syncProjects([{ id: '9', type: '技术项目', mockTeamSourceId: 'legacy:9' }, { id: 'child', parentProjectId: '9' }])
const parentRole = getSyncedProjectRoles('child')[0]
assert.equal(usePermissionStore.getState().toggleProjectRolePermissions(admin, 'child', { source: 'ipm', id: parentRole.id }, ['plan:导出'], true).ok, true)
assert.equal(hasPermission(member, 'child', 'plan:导出'), true)
const childLive = { currentLoginUser: member, selectedProject: { id: 'child' } }
assert.equal(canExecuteProjectTeamWrite(member, 'child', childLive, '9', 'plan:导出'), true)
useProjectTeamStore.getState().syncProjects([{ id: '1', type: '整机产品项目', sourceBid: 'EXT-001' }, { id: 'child', parentProjectId: '1' }])
assert.equal(canExecuteProjectTeamWrite(member, 'child', childLive, '9', 'plan:导出'), false)
console.log('PASS real project/resource actions, member removal and technical parent scope')

const { projectTeamRows } = load(path.resolve('src/lib/projectTeamPresentation.ts'))
const duplicate = { employeeId: 'DUP', name: member, roles: ['First'], roleCodes: ['ONE'], department: '', email: '', valueDelivery: '' }
const deduped = projectTeamRows({ members: [duplicate, { ...duplicate, roles: ['Second'], roleCodes: ['TWO'] }, { ...duplicate, employeeId: 'ANOTHER' }] })
assert.equal(deduped.length, 2)
assert.deepEqual(deduped[0].roleCodes, ['ONE', 'TWO'], 'duplicate employee rows merge memberships rather than losing roles')
console.log('PASS binding tokens and duplicate employee membership union')
